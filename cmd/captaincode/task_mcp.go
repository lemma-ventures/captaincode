package main

// `captain task mcp` - a stdio MCP server exposing the versioned task API
// (ROADMAP M4.2). Where the Euclid MCP server exposes memory tools, this
// server exposes the seven execution operations — plan, submit, inspect,
// events, artifacts, cancel, resume — so a host like Pi, Jido or an editor
// can delegate coding work to Captain through MCP rather than HTTP.
//
// Transport: newline-delimited JSON-RPC 2.0 on stdin/stdout (MCP stdio),
// the same transport as the Euclid MCP server. Each tool call constructs a
// TaskRequest envelope, posts it to the brain's /v1/task endpoint, and
// returns the response body as text content. The brain is the authority;
// the MCP server is a thin adapter that speaks MCP on one side and the
// versioned task API on the other.
//
// One internal lifecycle for HTTP and MCP: the same TaskRequest/TaskResponse
// envelope, the same error taxonomy, the same delegation lineage validation.
// A host that switches from HTTP to MCP does not get a different contract.

