// mcpTasksProtocolVersion is the protocol version that introduced the
// experimental Tasks capability. A client that requests this version gets
// task-level semantics; a client on an older version gets tools only.
const mcpTasksProtocolVersion = "2025-11-25"

// mcpTaskDefaultTTL is the default task lifetime in milliseconds (1 hour).
const mcpTaskDefaultTTL = 3600000

// mcpTaskPollInterval is the suggested polling interval in milliseconds.
const mcpTaskPollInterval = 5000

// mcpTaskResultTimeout is how long tasks/result blocks before returning
// an error suggesting the client poll with tasks/get instead.
const mcpTaskResultTimeout = 120 * time.Second

// mcpTask maps an MCP task to its Captain task. The MCP task ID is
// generated by this server (the receiver); the Captain task ID comes from
// the brain's submit response. The MCP task tracks the Captain task's
// lifecycle and translates it to the MCP task status vocabulary.
type mcpTask struct {
	ID          string
	CaptainID   string
	ToolName    string
	Status      string // working, input_required, completed, failed, cancelled
	StatusMsg   string
	CreatedAt   time.Time
	LastUpdated time.Time
	TTL         int64          // milliseconds
	Result      map[string]any // stored tool result when terminal
	ResultErr   *rpcError
}

// taskMCPSession is the per-connection state: the negotiated protocol
// version, whether the client declared tasks capability, and the task
// store. The task store is process-local — the brain has the durable
// state; this is the mapping layer that gives an MCP client task-level
// semantics over the HTTP task API.
type taskMCPSession struct {
	mu             sync.Mutex
	tasks          map[string]*mcpTask
	order          []string // task IDs in creation order, for tasks/list
	version        string   // negotiated protocol version
	clientHasTasks bool     // client declared tasks capability
}

func newTaskMCPSession() *taskMCPSession {
	return &taskMCPSession{tasks: make(map[string]*mcpTask)}
}

// lifecycleToMCPStatus maps Captain lifecycle states to MCP task statuses.
// The MCP spec defines five statuses: working, input_required, completed,
// failed, cancelled. Captain has nine states; the mapping is many-to-one.
func lifecycleToMCPStatus(s captaincode.LifecycleState) string {
	switch s {
	case captaincode.StateAdmitted, captaincode.StateRunning:
		return "working"
	case captaincode.StateWaitingForInput:
		return "input_required"
	case captaincode.StateSucceeded:
		return "completed"
	case captaincode.StateCancelled:
		return "cancelled"
	case captaincode.StateFailed, captaincode.StateExhausted, captaincode.StateInterrupted:
		return "failed"
	}
	return "working"
}

func (s *taskMCPSession) putTask(t *mcpTask) {
	s.mu.Lock()
	s.tasks[t.ID] = t
	s.order = append(s.order, t.ID)
	s.mu.Unlock()
}

func (s *taskMCPSession) getTask(id string) (*mcpTask, bool) {
	s.mu.Lock()
	t, ok := s.tasks[id]
	s.mu.Unlock()
	return t, ok
}

func (s *taskMCPSession) updateTask(id string, status, msg string) {
	s.mu.Lock()
	if t, ok := s.tasks[id]; ok {
		t.Status = status
		t.StatusMsg = msg
		t.LastUpdated = time.Now()
	}
	s.mu.Unlock()
}

func (s *taskMCPSession) allTasks() []*mcpTask {
	s.mu.Lock()
	out := make([]*mcpTask, 0, len(s.order))
	for _, id := range s.order {
		if t, ok := s.tasks[id]; ok {
			out = append(out, t)
		}
	}
	s.mu.Unlock()
	return out
}

// mcpTaskResult is the MCP Task object returned in responses.
type mcpTaskResult struct {
	TaskID        string `json:"taskId"`
	Status        string `json:"status"`
	StatusMessage string `json:"statusMessage,omitempty"`
	CreatedAt     string `json:"createdAt"`
	LastUpdatedAt string `json:"lastUpdatedAt"`
	TTL           *int64 `json:"ttl"`
	PollInterval  int64  `json:"pollInterval,omitempty"`
}

func toMCPTaskResult(t *mcpTask) mcpTaskResult {
	ttl := t.TTL
	return mcpTaskResult{
		TaskID:        t.ID,
		Status:        t.Status,
		StatusMessage: t.StatusMsg,
		CreatedAt:     t.CreatedAt.UTC().Format(time.RFC3339),
		LastUpdatedAt: t.LastUpdated.UTC().Format(time.RFC3339),
		TTL:           &ttl,
		PollInterval:  mcpTaskPollInterval,
	}
}

